# -*- coding: utf-8 -*-
"""A service layer's input rules, set on the QGIS layer (TCK-2343).

The rules are the service's (TCK-2330): read from ALIGN each time the layer
opens, the project reopens or the session comes back, and set again from
scratch, so a rule removed in ALIGN leaves QGIS too. The project keeps no
rule as a source of truth: ALIGN does.

What QGIS cannot take is left to ALIGN and said once, at the opening. ALIGN
judges every write anyway. When it refuses one (422), QGIS 3.44 passes its
field-by-field answer on (:func:`align_answer`); QGIS 3.34 only the reason
phrase, so :func:`explain_refusal` reads the edits waiting to be saved
against the rules the plugin set, rule by rule: QGIS holds one expression per
field, so each rule is kept on its own beside it, in the layer's custom
properties, to name only the one a value breaks.

Copyright (C) 2026 Geo Nova
SPDX-License-Identifier: GPL-2.0-or-later
"""
import json

from qgis.core import (
    Qgis,
    QgsAttributeEditorContainer,
    QgsAttributeEditorField,
    QgsEditFormConfig,
    QgsEditorWidgetSetup,
    QgsExpression,
    QgsExpressionContext,
    QgsExpressionContextUtils,
    QgsFieldConstraints,
    QgsOptionalExpression,
)

from ..form_rules import form_settings, rules_refusal
from ..i18n import tr
from ..qtcompat import qt_enum

_NOT_NULL = qt_enum(QgsFieldConstraints, "Constraint", "ConstraintNotNull")
_EXPRESSION = qt_enum(QgsFieldConstraints, "Constraint", "ConstraintExpression")
_HARD = qt_enum(QgsFieldConstraints, "ConstraintStrength", "ConstraintStrengthHard")
#: Each field's rules one by one (``{field: [{"expression", "message"}]}``), as JSON.
_CHECKS = "align/form_checks"


def layer_description(service_description, layer_id):
    """The described layer of a service, or ``None``."""
    for layer in (service_description or {}).get("layers") or []:
        if isinstance(layer, dict) and layer.get("layerId") == layer_id:
            return layer
    return None


def _layout(name):
    group = getattr(Qgis, "AttributeFormLayout", None)
    if group is not None and hasattr(group, name):
        return getattr(group, name)
    return getattr(QgsEditFormConfig, {"AutoGenerated": "GeneratedLayout", "DragAndDrop": "TabLayout"}[name])


def _plain_container(name, parent):
    """A container that shows its field and nothing of itself: no frame, no title."""
    container = QgsAttributeEditorContainer(name, parent)
    kinds = getattr(Qgis, "AttributeEditorContainerType", None)
    if kinds is not None and hasattr(container, "setType"):
        container.setType(kinds.Row)
    else:
        container.setIsGroupBox(True)
    container.setShowLabel(False)
    return container


def _reset(layer):
    """Back to what QGIS gives a field: what ALIGN no longer asks leaves too."""
    for index in range(layer.fields().count()):
        layer.setEditorWidgetSetup(index, QgsEditorWidgetSetup())
        layer.removeFieldConstraint(index, _NOT_NULL)
        layer.removeFieldConstraint(index, _EXPRESSION)
        layer.removeFieldAlias(index)
    layer.removeCustomProperty(_CHECKS)


def apply_form(layer, described):
    """Set a service layer's input rules on the QGIS layer.

    :param layer: the service layer (OAPIF)
    :param described: the layer as ALIGN describes it (``fields``, ``form``)
    :returns: what ALIGN alone checks, one line per field (``"field: rule"``)
    """
    _reset(layer)
    fields = layer.fields()
    for field in (described or {}).get("fields") or []:
        index = fields.indexOf(field.get("name", "")) if isinstance(field, dict) else -1
        if index >= 0 and field.get("alias"):
            layer.setFieldAlias(index, field["alias"])
    settings = [entry for entry in form_settings((described or {}).get("form"), (described or {}).get("fields"), tr) if fields.indexOf(entry["field"]) >= 0]
    left = []
    for entry in settings:
        index = fields.indexOf(entry["field"])
        layer.setEditorWidgetSetup(index, QgsEditorWidgetSetup(entry["widget"], entry["config"]))
        if entry["alias"]:
            layer.setFieldAlias(index, entry["alias"])
        if entry["not_null"]:
            layer.setFieldConstraint(index, _NOT_NULL, _HARD)
        if entry["expression"]:
            layer.setConstraintExpression(index, entry["expression"], entry["description"] or "")
            layer.setFieldConstraint(index, _EXPRESSION, _HARD)
        left.extend(tr("{}: {}").format(entry["alias"] or entry["field"], text) for text in entry["left_to_server"])
    checks = {entry["field"]: entry["checks"] for entry in settings if entry["checks"]}
    if checks:
        layer.setCustomProperty(_CHECKS, json.dumps(checks))
    _set_visibility(layer, {entry["field"]: entry["visibility"] for entry in settings if entry["visibility"]})
    return left


def _set_visibility(layer, conditions):
    """"Visible if": QGIS takes a condition on a container, so a field that
    has one sits in a container of its own; the form is generated as before
    when no field has one."""
    config = layer.editFormConfig()
    if not conditions:
        config.setLayout(_layout("AutoGenerated"))
        layer.setEditFormConfig(config)
        return
    config.clearTabs()
    root = config.invisibleRootContainer()
    fields = layer.fields()
    for index in range(fields.count()):
        name = fields.at(index).name()
        if name in conditions:
            container = _plain_container(name, root)
            container.addChildElement(QgsAttributeEditorField(name, index, container))
            container.setVisibilityExpression(QgsOptionalExpression(QgsExpression(conditions[name])))
            config.addTab(container)
        else:
            config.addTab(QgsAttributeEditorField(name, index, root))
    config.setLayout(_layout("DragAndDrop"))
    layer.setEditFormConfig(config)


def _pending_feature_ids(layer):
    buffer = layer.editBuffer()
    if buffer is None:
        return []
    ids = list(buffer.addedFeatures().keys()) + list(buffer.changedAttributeValues().keys())
    return list(dict.fromkeys(ids))


def _checks(layer):
    try:
        checks = json.loads(layer.customProperty(_CHECKS) or "{}")
    except ValueError:
        return {}
    return checks if isinstance(checks, dict) else {}


def _breaks(text, context):
    """Whether a rule's expression refuses the feature in ``context``; an
    expression QGIS cannot evaluate names nothing."""
    expression = QgsExpression(text)
    expression.prepare(context)
    value = expression.evaluate(context)
    return not expression.hasEvalError() and not value


def align_answer(layer):
    """ALIGN's own answer to the layer's last refused save, field by field,
    when QGIS passed it on; ``None`` otherwise."""
    return rules_refusal(layer.commitErrors())[1]


def explain_refusal(layer):
    """Why ALIGN refused to save a service layer's edits, as far as the
    plugin can tell: one line per feature and field, with the rules its value
    breaks. Empty when the edits meet every rule set on the layer: then a
    rule only ALIGN checks refused them."""
    lines = []
    fields = layer.fields()
    ruled = [(fields.indexOf(name), checks) for name, checks in _checks(layer).items() if fields.indexOf(name) >= 0 and isinstance(checks, list)]
    for feature_id in _pending_feature_ids(layer):
        feature = layer.getFeature(feature_id)
        if not feature.isValid():
            continue
        context = QgsExpressionContext(QgsExpressionContextUtils.globalProjectLayerScopes(layer))
        context.setFeature(feature)
        for index, checks in ruled:
            broken = [check["message"] for check in checks if isinstance(check, dict) and _breaks(check.get("expression", ""), context)]
            if broken:
                lines.append(tr("{}, {}: {}").format(_feature_label(layer, feature, feature_id), layer.attributeDisplayName(index), tr("; ").join(broken)))
    return lines


def _feature_label(layer, feature, feature_id):
    """A feature as ALIGN names it: its ``fid`` when the layer shows it; a new one has none yet."""
    if feature_id < 0:
        return tr("New feature")
    index = layer.fields().indexOf("fid")
    return tr("Feature {}").format(feature.attribute(index) if index >= 0 else feature_id)
